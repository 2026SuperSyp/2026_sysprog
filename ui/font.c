static const uint8_t *find_glyph(int ch)
{
    if (ch >= 'a' && ch <= 'z') ch -= 'a' - 'A';
    for (unsigned i = 0; i < sizeof glyphs / sizeof glyphs[0]; i++)
        if (glyphs[i].ch == ch) return glyphs[i].rows;
    return 0;
}

/* UTF-8 글자 하나를 읽고 다음 글자로 넘어간다. 끝이면 0. */
static int next_codepoint(const char **s)
{
    const unsigned char *p = (const unsigned char *)*s;
    if (!*p) return 0;
    int n = (*p >= 0xF0) ? 4 : (*p >= 0xE0) ? 3 : (*p >= 0xC0) ? 2 : 1;
    int cp = (n == 4) ? (*p & 0x07) : (n == 3) ? (*p & 0x0F) : (n == 2) ? (*p & 0x1F) : *p;
    p++;
    for (int i = 1; i < n && (*p & 0xC0) == 0x80; i++, p++)
        cp = (cp << 6) | (*p & 0x3F);
    *s = (const char *)p;
    return cp;
}

void ui_text(canvas_t *c, int x, int y, const char *s, color_t col)
{
    if (!c || !s) return;
    int cp;
    while ((cp = next_codepoint(&s)) != 0) {
        if (cp < 128) {
            const uint8_t *g = find_glyph(cp);
            for (int r = 0; g && r < 7; r++)
                for (int k = 0; k < 5; k++)
                    if (g[r] & (0x10 >> k)) ui_px(c, x + k, y + r, col);
            x += UI_FONT_W;
        } else {
            /* 한글 자리. 글꼴을 넣기 전까지는 빈 네모로 표시한다. */
            ui_line(c, x + 1, y + 1, x + 10, y + 1, col);
            ui_line(c, x + 1, y + 10, x + 10, y + 10, col);
            ui_line(c, x + 1, y + 1, x + 1, y + 10, col);
            ui_line(c, x + 10, y + 1, x + 10, y + 10, col);
            x += UI_KFONT_W;
        }
    }
}

int ui_text_w(const char *s)
{
    int w = 0, cp;
    if (!s) return 0;
    while ((cp = next_codepoint(&s)) != 0)
        w += (cp < 128) ? UI_FONT_W : UI_KFONT_W;
    return w;
}
